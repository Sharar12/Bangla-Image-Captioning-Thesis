            "        for ng in hyp_ngrams: hyp_freq[ng] += 1",
            "        all_ngrams = set(ref_freq.keys()) | set(hyp_freq.keys())",
            "        ref_vec = [ref_freq.get(ng, 0) for ng in all_ngrams]",
            "        hyp_vec = [hyp_freq.get(ng, 0) for ng in all_ngrams]",
