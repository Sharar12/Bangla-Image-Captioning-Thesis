"""
Generate Jupyter Notebook (.ipynb) versions of all .py files
with proper markdown sections, comments, and organized cells.
"""

import json
import os

CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))


def md_cell(source_lines):
    """Create a markdown cell."""
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": [line + "\n" if not line.endswith("\n") else line for line in source_lines],
    }


def code_cell(source_lines):
    """Create a code cell."""
    return {
        "cell_type": "code",
        "metadata": {},
        "source": [line + "\n" if not line.endswith("\n") else line for line in source_lines],
        "execution_count": None,
        "outputs": [],
    }


def empty_code_cell():
    return {
        "cell_type": "code",
        "metadata": {},
        "source": [],
        "execution_count": None,
        "outputs": [],
    }


def make_notebook(cells, title="Bangla Image Captioning"):
    """Assemble a complete .ipynb JSON structure."""
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.10.0",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def write_notebook(filename, notebook):
    path = os.path.join(CURRENT_DIR, filename)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(notebook, f, ensure_ascii=False, indent=1)
    print(f"Created: {filename}")


