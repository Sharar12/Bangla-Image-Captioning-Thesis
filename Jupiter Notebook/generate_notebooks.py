            "        visual_tokens = self.vision_projection(features)",
            "        logits = self.decoder(visual_tokens, input_ids)",
            "        if labels is None:",
            "            labels = input_ids.clone()",
            "            labels[labels == 0] = -100",
            "        shift_logits = logits[:, :-1, :].contiguous()",
            "        shift_labels = labels[:, 1:].contiguous()",
